MAX_RELEASE_ASSET = 1024 * 1024 * 1024
READ_BYTES = 1024 * 1024


def _verify_stream(source, expected_size: int, expected_hash: str, label: str):
    digest = hashlib.sha256()
    size = 0
    for chunk in iter(lambda: source.read(READ_BYTES), b""):
        size += len(chunk)
        if size > expected_size:
            raise DataError(f"Package content exceeds expected size: {label}")
        digest.update(chunk)
    if size != expected_size or digest.hexdigest() != expected_hash:
        raise DataError(f"Package content mismatch: {label}")


def _verify_zip(path: Path, expected: dict[str, dict]):
    with zipfile.ZipFile(path) as archive:
        members = archive.infolist()
        names = [member.filename for member in members]
        if len(names) != len(expected) or set(names) != set(expected):
            raise DataError(f"Package ZIP member inventory mismatch: {path.name}")
        for member in members:
            identity = expected[member.filename]
            size = identity.get("size", member.file_size)
            if member.file_size != size:
                raise DataError(f"Package ZIP member size mismatch: {member.filename}")
            with archive.open(member) as source:
                _verify_stream(source, size, identity["sha256"], member.filename)


class _PartsReader:
    """Read a split compressed stream in manifest order, with one file open."""

    def __init__(self, paths):
        self.paths = iter(paths)
        self.handle = None

    def read(self, size):
        if size <= 0:
            return b""
        while True:
            if self.handle is None:
                path = next(self.paths, None)
                if path is None:
                    return b""
                self.handle = path.open("rb")
            chunk = self.handle.read(min(size, READ_BYTES))
            if chunk:
                return chunk
            self.close()

    def close(self):
        if self.handle is not None:
            self.handle.close()
            self.handle = None


def verify_package(output: Path, *, catalog: dict | None = None) -> dict:
    """Read back a completed package without reparsing YAML or restoring files.

    This checks transport bytes against the already-validated canonical catalog
    and the recorded SQLite identity. It also works on existing release folders.
    Memory is bounded by a read buffer, codec window, and manifest inventories.
    New packages preserve the compressor-generated byte count. Older manifests
    use their recorded part sizes; this does not independently certify frame EOF.
    """
    output = Path(output)
    try:
        packaged_catalog = read_json(output / "catalog.json")
        if catalog is not None and packaged_catalog != catalog:
            raise DataError("Packaged catalog differs from the validated build")
        catalog = packaged_catalog
        release = read_json(output / "release.json")
        if release["build_id"] != catalog["build_id"] or release["scope"] != catalog["scope"]:
            raise DataError("Package release identity disagrees with its catalog")
        assets = {}
        for asset in release["assets"]:
            if asset["path"] in assets:
                raise DataError("Duplicate package asset")
            assets[asset["path"]] = asset
            with safe_relative(output, asset["path"]).open("rb") as source:
                _verify_stream(source, asset["size"], asset["sha256"], asset["path"])
        for metadata in (catalog["licenses"], catalog["document_index"]):
            path = safe_relative(output, metadata["path"])
            with path.open("rb") as source:
                _verify_stream(
                    source,
                    metadata.get("size", path.stat().st_size),
                    metadata["sha256"],
                    metadata["path"],
                )
        shards = {shard["path"]: shard for shard in catalog["shards"]}
        snapshots = {snapshot["source_id"]: snapshot for snapshot in catalog["snapshots"]}
        seen = set()
        for asset in release["assets"]:
            if asset["kind"] not in {"yaml-zip", "jsonl-zip"}:
                continue
            expected = {}
            for name in asset["members"]:
                if name not in shards or name in seen:
                    raise DataError("Package repeats or invents a YAML shard")
                shard = shards[name]
                if (shard["source_id"], shard["language"]) != (
                    asset["source_id"],
                    asset["language"],
                ):
                    raise DataError("Package ZIP source/language disagrees with its shard")
                seen.add(name)
                expected[name] = shard
            snapshot = snapshots[asset["source_id"]]
            expected["licenses.json"] = catalog["licenses"]
            expected[snapshot["manifest"]] = {"sha256": snapshot["manifest_sha256"]}
            _verify_zip(safe_relative(output, asset["path"]), expected)
        if seen != set(shards):
            raise DataError("Package is missing canonical YAML shards")
        provenance = {
            item["manifest"]: {"sha256": item["manifest_sha256"]} for item in catalog["snapshots"]
        }
        provenance.update(
            {
                "schemas/" + schema.name: {
                    "size": schema.stat().st_size,
                    "sha256": sha256_file(schema),
                }
                for schema in sorted(SCHEMAS.glob("*.json"))
            }
        )
        _verify_zip(output / "provenance-and-schemas.zip", provenance)
        used_parts = set()
        for database in release["databases"]:
            names = database["parts"]
            if not names:
                raise DataError("Package database has no compressed parts")
            for name in names:
                if name in used_parts or assets[name]["kind"] != "sqlite-zstd-part":
                    raise DataError("Package database has invalid or repeated parts")
                if (assets[name]["source_id"], assets[name]["language"]) != (
                    database["source_id"],
                    database["language"],
                ):
                    raise DataError("Package database part has a different source/language")
                used_parts.add(name)
            recorded_size = sum(assets[name]["size"] for name in names)
            if recorded_size != database.get("compressed_size", recorded_size):
                raise DataError("Package compressed size differs from compressor output")
            source = _PartsReader(safe_relative(output, name) for name in names)
            try:
                with zstandard.ZstdDecompressor().stream_reader(
                    source, read_across_frames=True
                ) as decoded:
                    _verify_stream(
                        decoded,
                        database["uncompressed_size"],
                        database["uncompressed_sha256"],
                        database["uncompressed_path"],
                    )
            finally:
                source.close()
        if used_parts != {
            name for name, asset in assets.items() if asset["kind"] == "sqlite-zstd-part"
        }:
            raise DataError("Package has unassigned database parts")
    except (
        OSError,
        KeyError,
        TypeError,
        ValueError,
        zipfile.BadZipFile,
        zstandard.ZstdError,
    ) as exc:
        raise DataError(f"Package read-back validation failed: {exc}") from exc
    return release


def _entry(root: Path, path: Path, **metadata) -> dict:
    return {
        "path": path.relative_to(root).as_posix(),
        "size": path.stat().st_size,
        "sha256": sha256_file(path),
        **metadata,
    }


def _zip_member(archive: zipfile.ZipFile, source: Path, name: str):
    info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.create_system = 3
    info.external_attr = 0o100644 << 16
    with source.open("rb") as incoming, archive.open(info, "w", force_zip64=True) as outgoing:
        shutil.copyfileobj(incoming, outgoing, 1024 * 1024)


class _PartsWriter:
    def __init__(self, root: Path, name: str, max_bytes: int):
        self.root, self.name, self.max_bytes = root, name, max_bytes
        self.paths: list[Path] = []
        self.handle = None
        self.size = 0

    def write(self, data: bytes):
        view = memoryview(data)
        total = len(data)
        while view:
            if self.handle is None:
                path = self.root / f"{self.name}.part{len(self.paths):04d}"
                self.paths.append(path)
                self.handle = path.open("wb")
                self.size = 0
            count = min(len(view), self.max_bytes - self.size)
            self.handle.write(view[:count])
            self.size += count
            view = view[count:]
            if self.size == self.max_bytes:
                self.handle.close()
                self.handle = None
        return total

    def flush(self):
        if self.handle:
            self.handle.flush()

    def close(self):
        if self.handle:
            self.handle.close()
            self.handle = None
        if len(self.paths) == 1:
            old = self.paths[0]
            new = self.root / self.name
            old.rename(new)
            self.paths[0] = new


def package_build(
    build: Path,
    output: Path,
    *,
    archive_bytes=128 * 1024 * 1024,
    part_bytes=MAX_RELEASE_ASSET,
    include_sqlite=True,
) -> Path:
    require_new_directory(output)
    if not (1024 <= archive_bytes <= MAX_RELEASE_ASSET // 2):
        raise DataError("ZIP input budget must be between 1 KiB and 512 MiB")
    if not (1024 <= part_bytes <= MAX_RELEASE_ASSET):
        raise DataError("Asset part size must be between 1 KiB and 1 GiB")
    catalog = verify_build(build)
    for name in ("catalog.json", "licenses.json", "documents.jsonl"):
        if (build / name).stat().st_size >= 2 * 1024**3:
            raise DataError(
                f"Metadata file {name} exceeds GitHub's 2 GiB asset limit. "
                "Build fewer sources per release; changing the YAML shard budget "
                "does not reduce the document index."
            )
    # Validation is required even for YAML-only releases. A checksum establishes
    # byte integrity, not schema validity, identity consistency, or permission.
    for _ in iter_records(build, catalog):
        pass
    staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    assets = []
    databases = []
    try:
        partitions: dict[tuple[str, str], list[dict]] = defaultdict(list)
        for shard in catalog["shards"]:
            partitions[(shard["source_id"], shard["language"])].append(shard)
        for (source_id, language), shards in sorted(partitions.items()):
            record_format = catalog["options"].get("record_format", "yaml")
            from .normalized import export_normalized

            normalized = staging / f"{source_id}.{language}.normalized.zip"
            export_normalized(build, normalized, source_id=source_id, catalog=catalog)
            assets.append(
                _entry(
                    staging,
                    normalized,
                    kind="normalized-jsonl-zip",
                    source_id=source_id,
                    language=language,
                )
            )
            groups: list[list[dict]] = []
            group: list[dict] = []
            size = 0
            for shard in shards:
                if group and size + shard["size"] > archive_bytes:
                    groups.append(group)
                    group, size = [], 0
                group.append(shard)
                size += shard["size"]
            if group:
                groups.append(group)
            for number, group in enumerate(groups):
                archive_path = safe_relative(
                    staging, f"{source_id}.{language}.{record_format}-{number:04d}.zip"
                )
                with zipfile.ZipFile(
                    archive_path,
                    "w",
                    compression=zipfile.ZIP_DEFLATED,
                    compresslevel=6,
                    allowZip64=True,
                ) as archive:
                    for shard in group:
                        _zip_member(archive, safe_relative(build, shard["path"]), shard["path"])
                    _zip_member(archive, build / "licenses.json", "licenses.json")
                    snapshot = next(s for s in catalog["snapshots"] if s["source_id"] == source_id)
                    _zip_member(
                        archive, safe_relative(build, snapshot["manifest"]), snapshot["manifest"]
                    )
                assets.append(
                    _entry(
                        staging,
                        archive_path,
                        kind=f"{record_format}-zip",
                        source_id=source_id,
                        language=language,
                        members=[shard["path"] for shard in group],
                    )
                )
            if include_sqlite:
                db_path = safe_relative(staging, f"{source_id}.{language}.sqlite3")
                if record_format == "jsonl":
                    from .normalized_database import build_normalized_database

                    build_normalized_database(normalized, db_path)
                else:
                    build_database(build, db_path, source_id=source_id, catalog=catalog)
                db_hash, db_size = sha256_file(db_path), db_path.stat().st_size
                writer = _PartsWriter(staging, db_path.name + ".zst", part_bytes)
                try:
                    with db_path.open("rb") as incoming:
                        read_size, compressed_size = zstandard.ZstdCompressor(
                            level=9, write_checksum=True
                        ).copy_stream(incoming, writer)
                finally:
                    writer.close()
                parts = [
                    _entry(
                        staging,
                        path,
                        kind="sqlite-zstd-part",
                        source_id=source_id,
                        language=language,
                    )
                    for path in writer.paths
                ]
                # Bind persisted lengths to bytes the compressor actually emitted.
                if read_size != db_size or sum(part["size"] for part in parts) != compressed_size:
                    raise DataError("SQLite bytes changed while compressing the package")
                assets.extend(parts)
                databases.append(
                    {
                        "source_id": source_id,
                        "language": language,
                        "schema_version": 2 if record_format == "jsonl" else 1,
                        "uncompressed_path": db_path.name,
                        "uncompressed_size": db_size,
                        "uncompressed_sha256": db_hash,
                        "compression": "zstd",
                        "compressed_size": compressed_size,
                        "parts": [part["path"] for part in parts],
                    }
                )
                db_path.unlink()
        for name in ["catalog.json", "licenses.json", "documents.jsonl"]:
            shutil.copyfile(build / name, staging / name)
            assets.append(_entry(staging, staging / name, kind="metadata"))
        with zipfile.ZipFile(
            staging / "provenance-and-schemas.zip", "w", compression=zipfile.ZIP_DEFLATED
        ) as archive:
            for snapshot in catalog["snapshots"]:
                _zip_member(
                    archive, safe_relative(build, snapshot["manifest"]), snapshot["manifest"]
                )
            for schema in sorted(SCHEMAS.glob("*.json")):
                _zip_member(archive, schema, "schemas/" + schema.name)
        assets.append(_entry(staging, staging / "provenance-and-schemas.zip", kind="metadata-zip"))
        if any(asset["size"] >= 2 * 1024**3 for asset in assets) or len(assets) + 2 > 1000:
            raise DataError(
                "Release exceeds GitHub asset limits; build fewer sources per release or change shard budget"
            )
        release = {
            "schema_version": 1,
            "build_id": catalog["build_id"],
            "scope": catalog["scope"],
            "assets": assets,
            "databases": databases,
            "sqlite_restore": "Concatenate each database's parts in listed order, then decompress the single zstd stream. Verify the uncompressed SHA-256.",
            "yaml_restore": "Extract YAML ZIP members into a common directory. The external catalog and document index locate a document's shard without decompressing the entire corpus.",
        }
        write_json(staging / "release.json", release)
        checksum_paths = sorted(path for path in staging.iterdir() if path.is_file())
        (staging / "SHA256SUMS").write_text(
            "".join(f"{sha256_file(path)}  {path.name}\n" for path in checksum_paths),
            encoding="utf-8",
        )
        verify_package(staging, catalog=catalog)
        os.replace(staging, output)
        return output / "release.json"
    finally:
        if staging.exists():
            shutil.rmtree(staging)
